"use client"

import { useMemo, type FC } from "react"
import {
  AssistantRuntimeProvider,
  useLocalRuntime,
  type ChatModelAdapter,
  type ChatModelRunResult,
  type SuggestionAdapter,
  type ThreadMessage,
} from "@assistant-ui/react"
import { AssistantModal } from "@/components/assistant-ui/assistant-modal"
import type { AnalysisResult } from "@/types"

// ---------------------------------------------------------------------------
// Static suggestion prompts shown when the chat is empty
// ---------------------------------------------------------------------------
const SUGGESTIONS = [
  { prompt: "Why did I get this match score?" },
  { prompt: "What are my key strengths for this role?" },
  { prompt: "What skills should I improve?" },
  { prompt: "How does my experience compare to the job requirements?" },
  { prompt: "Summarize my evaluation" },
] as const

const suggestionAdapter: SuggestionAdapter = {
  generate: async () => SUGGESTIONS,
}

// ---------------------------------------------------------------------------
// Build a system context message containing the full analysis results
// so the AI can answer specific follow-up questions about the evaluation.
// ---------------------------------------------------------------------------
function buildSystemContext(results: AnalysisResult): string {
  return `You are a helpful, conversational AI assistant embedded in a resume screening tool. The user has just submitted their resume and received an AI-powered evaluation. Answer their questions clearly and concisely using the context below.

=== RESUME ANALYSIS RESULTS ===
Candidate: ${results.candidateName}
Email: ${results.email}
Phone: ${results.phone}
Education: ${results.education}
Experience Years: ${results.experienceYears}
Previous Roles: ${results.previousRoles.join(", ")}

Scores (0-100):
- Overall Match: ${results.matchScore}
- Skills Match: ${results.skillsScore}
- Experience Relevance: ${results.experienceScore}
- Education Fit: ${results.educationScore}
- ATS Compatibility: ${results.atsScore}
- Resume Quality: ${results.resumeQualityScore}

Recommendation: ${results.recommendation}

Skills: ${results.skills.join(", ")}
Programming Languages: ${results.programmingLanguages.join(", ")}
Certifications: ${results.certifications.join(", ") || "None listed"}

Matched Skills: ${results.matchedSkills.join(", ")}
Missing Skills: ${results.missingSkills.join(", ") || "None"}
Additional Skills: ${results.additionalSkills.join(", ") || "None"}

Strengths:
${results.strengths.map((s) => `- ${s}`).join("\n")}

Areas for Improvement:
${results.weaknesses.map((w) => `- ${w}`).join("\n")}

Summary: ${results.summary}
=== END ANALYSIS RESULTS ===

Use this context to answer questions about the evaluation. If asked about something not covered above, be honest about the limitation. Keep answers friendly and helpful.`
}

// ---------------------------------------------------------------------------
// Extract the plain-text content from a ThreadMessage.
// Messages from assistant-ui store their text as an array of { type:"text", text } parts.
// ---------------------------------------------------------------------------
function extractMessageText(message: ThreadMessage): string {
  const content = message.content
  if (typeof content === "string") return content
  return (content as ReadonlyArray<{ type: string; text?: string }>)
    .filter((p) => p.type === "text")
    .map((p) => p.text ?? "")
    .join("")
}

// ---------------------------------------------------------------------------
// ChatModelAdapter — called by the runtime every time the user sends a message.
// Prepends the analysis context as a system message and proxies to /api/chat.
// ---------------------------------------------------------------------------
function createChatModelAdapter(contextMessage: string): ChatModelAdapter {
  return {
    async run(options): Promise<ChatModelRunResult> {
      const { messages, abortSignal } = options

      // Convert runtime messages to the format expected by our API route.
      // We only include user and assistant messages — system messages
      // generated by the runtime are replaced by our own context.
      const userMessages = messages
        .filter((m) => m.role === "user" || m.role === "assistant")
        .map((m) => ({
          role: m.role as "user" | "assistant",
          content: extractMessageText(m),
        }))

      const apiMessages = [
        { role: "system", content: contextMessage },
        ...userMessages,
      ]

      const response = await fetch("/api/chat", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ messages: apiMessages }),
        signal: abortSignal,
      })

      if (!response.ok) {
        const errorData = await response.json().catch(() => ({}))
        throw new Error(
          (errorData as { error?: string }).error ??
            `Chat API error (${response.status})`
        )
      }

      const data = (await response.json()) as { content: string }

      return {
        content: [{ type: "text", text: data.content }],
      }
    },
  }
}

// ---------------------------------------------------------------------------
// ResultsChat — the top-level component to drop into the results page.
// Wraps AssistantModal with a runtime pre-loaded with analysis context.
// ---------------------------------------------------------------------------
export const ResultsChat: FC<{ results: AnalysisResult }> = ({ results }) => {
  // Build the system context once and keep it stable across renders.
  const contextMessage = useMemo(() => buildSystemContext(results), [results])

  // Create the chat adapter, also stable.
  const chatModelAdapter = useMemo(
    () => createChatModelAdapter(contextMessage),
    [contextMessage]
  )

  // Initialize the local runtime with our adapter + static suggestions.
  const runtime = useLocalRuntime(chatModelAdapter, {
    adapters: {
      suggestion: suggestionAdapter,
    },
  })

  return (
    <AssistantRuntimeProvider runtime={runtime}>
      <AssistantModal hideAttachments />
    </AssistantRuntimeProvider>
  )
}
